# ---------------------------------------------------------------------------
# emit.R : template filling and writing the per-country folders.
# Templates use {{key}} placeholders (plain substitution, no regex).
# ---------------------------------------------------------------------------

fill_template <- function(tpl, vals) {
  for (k in names(vals)) {
    key   <- paste0("{{", k, "}}")
    parts <- strsplit(paste0(tpl, "\001"), key, fixed = TRUE)[[1]]
    tpl   <- sub("\001$", "", paste(parts, collapse = as.character(vals[[k]])))
  }
  tpl
}

emit_country <- function(r, out_root = "countries") {
  dir <- file.path(out_root, r$iso3)
  dir.create(dir, recursive = TRUE, showWarnings = FALSE)
  s <- r$settings

  # 1. data and regime CSVs
  utils::write.csv(r$fx_data, file.path(dir, paste0(r$iso3, "_fx_data.csv")), row.names = FALSE)
  utils::write.csv(r$fit$regimes, file.path(dir, paste0(r$iso3, "_regimes.csv")), row.names = FALSE)

  # 2. standalone script (model code inlined from R/fit.R)
  fit_code <- paste(readLines("R/fit.R", warn = FALSE), collapse = "\n")
  script <- fill_template(
    paste(readLines("templates/country_script.R.tpl", warn = FALSE), collapse = "\n"),
    list(
      iso3 = r$iso3, name = r$name, ccy = r$fit$ccy, date = format(Sys.Date()),
      regressors = paste(sprintf('"%s"', s$regressors), collapse = ", "),
      h = s$h, breaks = s$breaks, ic = s$ic, frequency = s$frequency,
      numeraire = s$numeraire, fit_code = fit_code
    )
  )
  writeLines(script, file.path(dir, paste0(r$iso3, "_script.R")))

  # 3. the page
  qmd <- fill_template(
    paste(readLines("templates/country.qmd.tpl", warn = FALSE), collapse = "\n"),
    list(iso3 = r$iso3, name = r$name, ccy = r$fit$ccy, numeraire = s$numeraire,
         start = format(min(r$fx_data$date)), end = format(max(r$fx_data$date)))
  )
  writeLines(qmd, file.path(dir, "index.qmd"))
  invisible(dir)
}

# Sidebar grouped by World Bank region, written to _sidebar.yml
emit_sidebar <- function(meta, file = "_sidebar.yml") {
  meta <- meta[order(meta$region, meta$name), ]
  sections <- lapply(split(meta, meta$region), function(m) {
    list(section = m$region[1],
         contents = lapply(seq_len(nrow(m)), function(i)
           list(href = file.path("countries", m$iso3[i], "index.qmd"), text = m$name[i])))
  })
  names(sections) <- NULL
  txt <- yaml::as.yaml(list(website = list(sidebar = list(contents = sections))))
  writeLines(c("# GENERATED by build.R - do not edit", txt), file)
}
